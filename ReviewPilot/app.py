 " scores = {}\n",
 " for theme, spec in THEMES.items():\n",
 " hits = count_hits(text, spec[\"keywords\"]) # type: ignore[arg-type]\n",
 " scores[theme] = min(1.0, 0.5 + 0.25 * (hits - 1)) if hits else 0.0\n",
 " out.append(scores)\n",
 " return out\n",
